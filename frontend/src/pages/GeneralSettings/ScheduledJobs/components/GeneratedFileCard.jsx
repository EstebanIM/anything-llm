import { useState } from "react";
import { useTranslation } from "react-i18next";
import { LoaderCircle, Download, File } from "lucide-react";
import StorageFiles from "@/models/files";
import showToast from "@/utils/toast";
import { humanFileSize } from "@/utils/numbers";

// File extension → badge colors and type label. Other extensions show the
// extension itself (language-neutral) on a grey badge.
const FILE_DISPLAY_MAP = {
  pptx: {
    badge: "PPT",
    color: "bg-orange-100 text-orange-800",
    type: "powerpoint",
  },
  ppt: {
    badge: "PPT",
    color: "bg-orange-100 text-orange-800",
    type: "powerpoint",
  },
  pdf: { badge: "PDF", color: "bg-red-100 text-red-800", type: "pdf" },
  doc: { badge: "DOC", color: "bg-blue-100 text-blue-800", type: "word" },
  docx: { badge: "DOC", color: "bg-blue-100 text-blue-800", type: "word" },
  xls: {
    badge: "XLS",
    color: "bg-green-100 text-green-800",
    type: "spreadsheet",
  },
  xlsx: {
    badge: "XLS",
    color: "bg-green-100 text-green-800",
    type: "spreadsheet",
  },
  csv: {
    badge: "CSV",
    color: "bg-green-100 text-green-800",
    type: "spreadsheet",
  },
};

function getFileDisplayInfo(filename, t) {
  const parts = filename?.split(".") ?? [];
  const extension = parts.length > 1 ? parts.pop().toLowerCase() : "";
  const known = FILE_DISPLAY_MAP[extension];
  return {
    badge: known?.badge ?? extension.slice(0, 4).toUpperCase(),
    color: known?.color ?? "bg-zinc-200 text-zinc-800",
    type: t(`scheduledJobs.file.types.${known?.type ?? "generic"}`),
  };
}

// Card representing a file generated by a job run. Streams the file from
// the storage API on download via dynamic import of file-saver.
export default function GeneratedFileCard({ file }) {
  const { t } = useTranslation();
  const [downloading, setDownloading] = useState(false);
  const { badge, color, type } = getFileDisplayInfo(file.filename, t);
  const name = file.filename || t("scheduledJobs.file.unknown");
  const bytes =
    file.fileSize === null ||
    file.fileSize === undefined ||
    file.fileSize === ""
      ? NaN
      : Number(file.fileSize);
  const size = Number.isFinite(bytes) ? humanFileSize(bytes, true, 1) : null;

  const handleDownload = async () => {
    if (downloading || !file.storageFilename) return;
    setDownloading(true);
    try {
      const blob = await StorageFiles.download(file.storageFilename);
      if (!blob) throw new Error("Failed to download file");
      const { saveAs } = await import("file-saver");
      saveAs(blob, file.filename || file.storageFilename);
    } catch {
      showToast(t("scheduledJobs.file.downloadFailed"), "error");
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div className="flex items-center justify-between gap-3 bg-zinc-800 light:bg-slate-100 rounded-lg p-3">
      <div className="flex items-center gap-3 min-w-0">
        <div
          aria-hidden="true"
          className={`${color} rounded-lg flex items-center justify-center shrink-0 h-10 w-10 text-xs font-semibold`}
        >
          {badge || <File strokeWidth={1.5} size={18} />}
        </div>
        <div className="flex flex-col min-w-0">
          <p
            className="text-sm text-white light:text-slate-950 truncate"
            title={name}
          >
            {name}
          </p>
          <p className="text-sm text-zinc-400 light:text-slate-600">
            {[size, type].filter(Boolean).join(" · ")}
          </p>
        </div>
      </div>
      {file.storageFilename && (
        <button
          type="button"
          onClick={handleDownload}
          aria-busy={downloading || undefined}
          aria-disabled={downloading || undefined}
          aria-label={t("scheduledJobs.file.download", { name })}
          title={t("scheduledJobs.file.download", { name })}
          className="border-none inline-flex items-center justify-center shrink-0 w-11 h-11 md:w-8 md:h-8 rounded-full text-zinc-400 light:text-slate-700 hover:text-zinc-50 light:hover:text-slate-950 hover:bg-white/10 light:hover:bg-slate-200 transition-colors duration-quick ease-smooth aria-disabled:cursor-wait"
        >
          {downloading ? (
            <LoaderCircle
              strokeWidth={1.5}
              size={16}
              aria-hidden="true"
              className="motion-safe:animate-spin"
            />
          ) : (
            <Download strokeWidth={1.5} size={16} aria-hidden="true" />
          )}
        </button>
      )}
    </div>
  );
}
